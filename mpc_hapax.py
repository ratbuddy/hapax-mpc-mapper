SN_XSTICK = re.compile(r'\b(xs|xstk|xstick|cross|crossstick|sidestick|side)\b')
SN_RIM = re.compile(r'\b(rm|rim|rimshot|rims)\b')
SN_ARTIC = re.compile(r'\b(e|edge|dr|drag|fl|flam|roll|rl|ghost|gh|buzz|br|brush|swa|swb|sw|skl|skr|sl|bc|wo|rel|mg)\b')
