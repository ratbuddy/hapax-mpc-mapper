# --- Hapax text rules (template.txt: names = alphanumeric ASCII plus ' ', '_', '-', '+') --------
def hx(s, maxlen=None):
    s = s.replace('#', 's').replace('&', ' and ').replace('/', '-').replace('.', ' ')
    s = re.sub(r'[^A-Za-z0-9 _+\-]', ' ', s)
    s = re.sub(r'\s+', ' ', s).strip(' -_')
    if maxlen and len(s) > maxlen:
        s = s[:maxlen].rstrip(' -_')
    return s

def note_name(n):
    return f'{NOTE_NAMES[n % 12]}{n // 12 - 2}'   # MPC/Hapax style: 60 = C3

# --- source readers --------------------------------------------------------------------------
def load_acvs(path):
    b = open(path, 'rb').read()
    pos, out = 0, b''
    while pos < len(b) and b[pos:pos + 2] == b'\x1f\x8b':
        d = zlib.decompressobj(31)
        out += d.decompress(b[pos:])
        pos = len(b) - len(d.unused_data)
    if not out:
        raise ValueError('not a gzip ACVS container')
    i = out.find(b'{')
    hdr = out[:i].decode('ascii', 'replace').split('\n')
    return [h for h in hdr if h], json.loads(out[i:])

def active_layers_json(inst):
    res = []
    for l in inst.get('layersv', []):
        if not l.get('active', False):
            continue
        name = (l.get('sampleName') or '').strip()
        if name or l.get('oscillatorMode'):
            res.append({'sample': name or f'osc{l.get("oscillatorType")}',
                        'vs': int(l.get('velocityStart', 0)), 've': int(l.get('velocityEnd', 127)),
                        'osc': bool(l.get('oscillatorMode'))})
    return res

def read_track(path):
    hdr, j = load_acvs(path)
    return read_track_data(j.get('data', j), os.path.splitext(path)[1].lower()[1:], hdr[1] if len(hdr) > 1 else '')

def read_track_data(d, fmt='xtd', app=''):
    """Same as read_track, for a track dict (a track file's data, or one entry of a project's tracks)."""
    prog = d.get('program', {})
    ptype = prog.get('type')
    name = prog.get('name') or d.get('name') or 'Untitled'
    insts = prog.get('drum', {}).get('instruments', [])
    nfp = prog.get('padNoteMap', {}).get('noteForPad', {})
    out = {'name': name, 'fmt': fmt, 'app': app}
    if ptype == 0:
        out['kind'] = 'drum'
        pads = []
        for i, inst in enumerate(insts):
            layers = active_layers_json(inst)
            if not layers:
                continue
            note = nfp.get(f'value{i}')
            pads.append({'pad': i, 'note': note, 'layers': layers,
                         'zone': inst.get('zonePlayTime'), 'artic': inst.get('articulationType', 0)})
        out['pads'] = pads
        out['map_source'] = 'program.padNoteMap.noteForPad' if nfp else None
    elif ptype == 1:
        out['kind'] = 'keygroup'
        n = int(prog.get('keygroup', {}).get('numKeygroups', len(insts)))
        zones = []
        for inst in insts[:n]:
            layers = active_layers_json(inst)
            if layers:
                zones.append((int(inst.get('lowNote', 0)), int(inst.get('highNote', 127)), len(layers),
                              any(l['osc'] for l in layers)))
        out['zones'] = zones
    else:
        out['kind'] = f'other(type {ptype})'
    return out

def read_xpm(path):
    root = ET.parse(path).getroot()
    prog = root.find('Program')
    if prog is None:
        return {'name': os.path.basename(path), 'fmt': 'xpm', 'kind': 'other(no Program)'}
    ptype = (prog.get('type') or '').lower()
    name = (prog.findtext('ProgramName') or os.path.splitext(os.path.basename(path))[0]).strip()
    out = {'name': name, 'fmt': 'xpm', 'app': root.findtext('Version/Application_Version') or ''}
    insts = []
    for inst in prog.iter('Instrument'):
        num = inst.get('number')
        if num is None:
            continue
        layers = []
        for l in inst.iter('Layer'):
            if (l.findtext('Active') or 'True').strip().lower() != 'true':
                continue
            s = (l.findtext('SampleName') or '').strip()
            if s:
                layers.append({'sample': s, 'vs': int(float(l.findtext('VelStart') or 0)),
                               've': int(float(l.findtext('VelEnd') or 127)), 'osc': False})
        insts.append((int(num), inst, layers))
    base = min((n for n, _, _ in insts), default=1)
    if ptype == 'drum':
        pn = {int(p.get('number')): int(p.findtext('Note')) for p in prog.iter('PadNote') if p.findtext('Note')}
        pbase = min(pn, default=1)
        out['kind'] = 'drum'
        out['pads'] = []
        for num, inst, layers in insts:
            if not layers:
                continue
            i = num - base
            out['pads'].append({'pad': i, 'note': pn.get(i + pbase), 'layers': layers,
                                'zone': inst.findtext('ZonePlay'), 'artic': 0})
        out['map_source'] = 'PadNoteMap' if pn else None
    elif ptype == 'keygroup':
        out['kind'] = 'keygroup'
        zones = []
        for num, inst, layers in insts:
            if layers:
                zones.append((int(inst.findtext('LowNote') or 0), int(inst.findtext('HighNote') or 127), len(layers), False))
        out['zones'] = zones
    else:
        out['kind'] = f'other({ptype})'
    return out

