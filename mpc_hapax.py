NOISE_PARTS = {'chain', 'round robin', 'kit', 'acoustic', 'electronic', 'mpc', 'mpc2', 'mpc3'}
HAT_PEDAL = re.compile(r'\b(ped|pedal|foot|pc|po|pdl|splash|spl)\b')
HAT_OPEN = re.compile(r'\b(open|opn|op|oh|ohh|half|ho|hlf|loose|sizzle)\b')
HAT_CLOSED = re.compile(r'\b(closed|cls|clsd|cl|ch|chh|cc|ce|ct|tight|tip|shut|short)\b')
TOM_LOW = re.compile(r'\b(floor|flr|fl|ft|tf|low|lo|lw)\b')
TOM_HIGH = re.compile(r'\b(rack|rk|tr|rt|high|hi|hgh)\b')
