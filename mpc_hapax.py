def wav_seconds(path):
    try:
        with open(path, 'rb') as f:
            b = f.read(1 << 16)
        i = b.find(b'fmt ')
        ch, sr = struct.unpack('<HI', b[i + 10:i + 16]); bits = struct.unpack('<H', b[i + 22:i + 24])[0]
        j = b.find(b'data'); n = struct.unpack('<I', b[j + 4:j + 8])[0]
        return n / (sr * ch * bits / 8)
    except Exception:
        return None

def build_sounds(prog, wav_lookup):
    """One sound per distinct MIDI note (pads sharing a note collapse into one lane)."""
    by_note = defaultdict(list)
    for p in prog['pads']:
        by_note[p['note']].append(p)
    sounds = []
    for note, pads in by_note.items():
        pads.sort(key=lambda p: p['pad'])
        prim = pads[0]
        sample = prim['layers'][0]['sample']
        role, sub, ci = classify(sample)
        sounds.append({'note': note, 'pads': pads, 'sample': sample, 'role': role, 'sub': sub,
                       'desc': descriptor(sample, role, ci), 'pad': prim['pad'],
                       'size': tom_size(sample) if role == 'tom' else None,
                       'melodic_label': (sample.split('-')[ci].strip().title() if (role == 'melodic' and ci is not None) else '')})
    # hats with no open/closed keyword: longer sample = open
    hats = [s for s in sounds if s['role'] == 'hat' and s['sub'] is None]
    if hats and not any(s['role'] == 'hat' and s['sub'] == 'open' for s in sounds):
        durs = [(wav_seconds(wav_lookup(s['sample'])) or 0, s) for s in hats]
        if len(durs) >= 2:
            durs.sort(key=lambda x: x[0])
            if durs[-1][0] > 0:
                durs[-1][1]['sub'] = 'open'; durs[-1][1]['inferred'] = 'open (longest hat)'
                for _, s in durs[:-1]:
                    if s['sub'] is None:
                        s['sub'] = 'closed'; s['inferred'] = 'closed (shorter hat)'
    return sounds

def lane_label(s, maxlen):
    if s['role'] == 'hat': base = HAT_LABEL.get(s['sub'], 'HH')
    elif s['role'] == 'tom': base = TOM_LABEL.get(s['sub'], 'Tom')
    elif s['role'] == 'rim': base = RIM_LABEL.get(s['sub'], 'Rim')
    elif s['role'] == 'melodic': base = s.get('melodic_label', '')
    else: base = ROLE_LABEL.get(s['role'], '')
    desc = s['desc']
    stem = base.lower()[:4]
    redundant = {'rack', 'floor', 'tom'} if s['role'] == 'tom' else set()
    if stem:   # drop words that just repeat the label: "Bass Drove BassHit" -> "Bass Drove Hit"
        desc = ' '.join(re.sub(rf'^{re.escape(stem)}[a-z]*', '', w, flags=re.I) if w.lower().startswith(stem) and len(w) > len(stem) + 1
                        else ('' if w.lower().startswith(stem) else w) for w in desc.split() if w.lower() not in redundant)
        desc = ' '.join(desc.split())
    name = f'{base} {desc}' if base and desc else (base or desc or s['sample'])
    return hx(name, maxlen) or f'Pad {pad_label(s["pad"])}'

def pad_label(i):
    return f'{"ABCDEFGH"[i // 16] if i < 128 else "?"}{i % 16 + 1:02d}'

def assign_lanes(sounds):
    free = sorted(sounds, key=lambda s: s['pad'])
    page1 = [None] * 8
    for slot, (_, prefs) in enumerate(PAGE1):
        for role, sub in prefs:
            cands = [s for s in free if s['role'] == role and (sub is None or s['sub'] == sub)]
            if role == 'tom' and cands:      # low slot: floor/biggest first; high slot: rack/smallest first
                rank = {'low': 0, 'mid': 1, 'high': 2, None: 1}
                key = lambda s: (rank[s['sub']], -(s['size'] or 0), s['pad'])
                cands.sort(key=key)
                if slot == 5:
                    cands.sort(key=lambda s: (-rank[s['sub']], s['size'] or 99, s['pad']))
            if cands:
                page1[slot] = cands[0]; free.remove(cands[0]); break
    order = {r: i for i, r in enumerate(FILL_ORDER)}
    best = lambda s: (s['sub'] == 'artic', s['pad'])          # main hits before chokes/bells/drags
    empty = [i for i in range(8) if page1[i] is None]
    while empty and free:                                      # one of each role per pass: crash, ride, ...
        took = False
        for role in FILL_ORDER:
            if not empty: break
            cands = sorted((s for s in free if s['role'] == role), key=best)
            if cands:
                page1[empty.pop(0)] = cands[0]; free.remove(cands[0]); took = True
        if not took: break
    free.sort(key=lambda s: (order.get(s['role'], 99), s['sub'] == 'artic', s['pad']))
    lanes = [s for s in page1 if s is not None] if not free else page1
    lanes = [s for s in lanes if s is not None]
    rest = free
    pages = [lanes + rest[:16 - len(lanes)]]
    rest = rest[16 - len(lanes):]
    while rest:
        pages.append(rest[:16]); rest = rest[16:]
    return pages

